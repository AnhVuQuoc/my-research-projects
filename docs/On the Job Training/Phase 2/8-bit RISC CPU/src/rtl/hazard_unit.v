// Module      : hazard_unit
// Project     : 8-bit RISC CPU, 5-stage pipeline (8-bit upgrade of the 4-bit CPU)
// Author      : Vu Quoc Anh (SE203519)
// Course      : Phase 1 Capstone, Lecturer: Shivashish Pal
// Stage       : ID (looks at ID and EX)
// Job         : Stalls the instruction in ID for exactly 1 cycle when
//               (1) load-use: EX holds LD and ID reads its rd on port A or B, or
//               (2) flag: ID holds BZ/BNZ and EX writes the Zero flag.
//               A stall holds IF/ID (ir_load = 0) and puts a bubble into ID/EX;
//               the PC hold is generated by halt_unit (pc_en = ~stall & ~halt).
// Ports       :
//   id_ra, id_rb [2:0]          in   registers ID reads (from control_unit)
//   id_uses_a, id_uses_b        in   ID really reads port A / B
//   id_is_bz, id_is_bnz         in   ID holds a conditional branch
//   ex_rd [2:0], ex_reg_we, ex_wb_sel, ex_zero_we   in   instruction in EX
//   load_use_stall, flag_stall  out  reasons (trace)
//   stall, ir_load, id_ex_bubble out stall; ~stall to IF/ID; stall to ID/EX
// Connections : instance HU in cpu_top; tested by tb_hazard_unit
// =============================================================================
`timescale 1ns / 1ps
`default_nettype none

module hazard_unit (
    input  wire [2:0] id_ra,
    input  wire [2:0] id_rb,
    input  wire       id_uses_a,
    input  wire       id_uses_b,
    input  wire       id_is_bz,
    input  wire       id_is_bnz,
    input  wire [2:0] ex_rd,
    input  wire       ex_reg_we,
    input  wire       ex_wb_sel,
    input  wire       ex_zero_we,
    output wire       load_use_stall,
    output wire       flag_stall,
    output wire       stall,
    output wire       ir_load,
    output wire       id_ex_bubble
);

    wire ex_is_load = ex_reg_we & ex_wb_sel;            // only LD has both = 1
    wire a_match    = id_uses_a & (id_ra == ex_rd);
    wire b_match    = id_uses_b & (id_rb == ex_rd);

    assign load_use_stall = ex_is_load & (a_match | b_match);
    assign flag_stall     = (id_is_bz | id_is_bnz) & ex_zero_we;
    assign stall          = load_use_stall | flag_stall;
    assign ir_load        = ~stall;
    assign id_ex_bubble   =  stall;

endmodule

`default_nettype wire
